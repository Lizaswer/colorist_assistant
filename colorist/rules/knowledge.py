_SHADE_RE = re.compile(r"^\s*(\d{1,2})\s*[/.,]\s*(\d{1,2})\s*$")


def parse_shade(shade: str) -> tuple[int, str]:
    """'7/1' -> (7, '1'). '7.43' -> (7, '43'). Ошибка, если формат не понятен."""
    match = _SHADE_RE.match(shade)
    if not match:
        raise ValueError(f"Не удалось разобрать оттенок: {shade!r}")
    return int(match.group(1)), match.group(2)


def grey_natural_share(grey_percent: int) -> float:
    for threshold, share in GREY_NATURAL_SHARE:
        if grey_percent >= threshold:
            return share
    return 0.0
